// Node test/parallel-style: node:console writer surface. Reached via require (the bare `console`
// global is not visible in the harness eval scope). We exercise the methods for side effect only —
// they must not throw — since the harness captures the completion value, not stdout.
const console = require("node:console");

test("the console module exposes the standard writers", () => {
  assert.strictEqual(typeof console, "object", "console module is an object");
  assert.strictEqual(typeof console.log, "function", "console.log");
  assert.strictEqual(typeof console.error, "function", "console.error");
  assert.strictEqual(typeof console.warn, "function", "console.warn");
  assert.strictEqual(typeof console.info, "function", "console.info");
});

test("the writers accept varied arguments without throwing", () => {
  console.log("conformance", 1, true, { a: 1 }, [1, 2, 3]);
  console.error("err-channel", null);
  console.warn("warn-channel");
  console.info("info-channel", "%s=%d", "x", 2);
  // Reaching here without a throw is the pass signal for the writer surface.
  assert.ok(true, "all writers returned without throwing");
});
